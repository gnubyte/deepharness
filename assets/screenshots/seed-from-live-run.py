#!/usr/bin/env python3
"""Turn a live screenshot run into the seeded chat and demo project the screenshot mode replays.

    Vision --snapshot <folder> --snapshot-live <aws-profile>     # a real run on Amazon Bedrock
    python3 assets/screenshots/seed-from-live-run.py <folder>

<folder> holds chat-transcript.json, project-before/ and project-after/ from the live run. This rewrites
Sources/VisionMacApp/Snapshot/SnapshotChat.swift and SnapshotProject.swift; build, then run
`Vision --snapshot <folder>` (no live run) to take the pictures from them.
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(REPO, "Sources", "VisionMacApp", "Snapshot")
SKIP_DIRS = {".git", "__pycache__", ".venv", ".baseline", ".scratch"}
INDENT = " " * 8


def read_tree(root):
    files = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for name in sorted(filenames):
            if name.endswith(".pyc") or name == ".DS_Store":
                continue
            path = os.path.join(dirpath, name)
            with open(path, encoding="utf-8") as handle:
                files[os.path.relpath(path, root)] = handle.read()
    return files


def raw_literal(text):
    """A Swift raw multi-line string literal (#\"\"\"…\"\"\"#) holding `text` without its final newline."""
    if '"""#' in text:
        raise SystemExit('text contains """#, which a raw literal cannot hold')
    body = text[:-1] if text.endswith("\n") else text
    lines = [INDENT + line if line else "" for line in body.split("\n")]
    return '#"""\n' + "\n".join(lines) + "\n" + INDENT + '"""#'


def dictionary(name, doc, files):
    parts = [f"    /// {doc}", f"    static let {name}: [String: String] = ["]
    parts += [f'        "{path}": {raw_literal(text)},' for path, text in files.items()]
    if not files:
        parts.append("        :")
    parts.append("    ]")
    return "\n".join(parts)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    run = sys.argv[1]
    with open(os.path.join(run, "chat-transcript.json"), encoding="utf-8") as handle:
        transcript = json.load(handle)
    before = read_tree(os.path.join(run, "project-before"))
    after = read_tree(os.path.join(run, "project-after"))
    changes = {path: text for path, text in after.items() if before.get(path) != text}

    chat = json.dumps(transcript, indent=2, sort_keys=True, ensure_ascii=False)
    with open(os.path.join(OUT, "SnapshotChat.swift"), "w", encoding="utf-8") as handle:
        handle.write(
            "// The seeded chat: a real run of the app on Amazon Bedrock, as `Vision --snapshot <folder> --snapshot-live\n"
            "// <aws-profile>` saved it (chat-transcript.json). Generated by assets/screenshots/seed-from-live-run.py.\n\n"
            "enum SnapshotChat {\n"
            f"    static let json = {raw_literal(chat)}\n"
            "}\n")
    with open(os.path.join(OUT, "SnapshotProject.swift"), "w", encoding="utf-8") as handle:
        handle.write(
            "// The demo project the screenshot mode works in, before and after the seeded chat's run. Generated by\n"
            "// assets/screenshots/seed-from-live-run.py.\n\n"
            "enum SnapshotProject {\n"
            f'{dictionary("files", "The demo project as the agent finds it.", before)}\n\n'
            f'{dictionary("changes", "What the seeded chat run changed and added.", changes)}\n'
            "}\n")
    print(f"{len(transcript['rows'])} chat rows; {len(before)} project files, {len(changes)} changed by the run")


if __name__ == "__main__":
    main()
